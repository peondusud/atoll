//go:build ignore

// upcase_gen writes upcase_table.go: the NTFS upcase table that Windows 7 to
// 10 and mkntfs write (specs.md §15.8), derived from Unicode 5.1.0 data.
//
// The rule: for each BMP character c whose simple uppercase (UnicodeData
// field 12) is U, keep c → U only when the simple lowercase of U (field 13)
// is c. docs/research/nfc-and-case-folding.md §4.3 shows that this rule gives
// the real table, entry for entry.
//
// Usage, from internal/names:
//
//	curl -o /tmp/UnicodeData-5.1.0.txt https://raw.githubusercontent.com/unicode-org/unicodetools/main/unicodetools/data/ucd/5.1.0-Update/UnicodeData.txt
//	go run upcase_gen.go /tmp/UnicodeData-5.1.0.txt
//
// The input's SHA-256 must be ucdSHA256 below. Unicode data is under the
// Unicode License v3.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

const ucdSHA256 = "8bd83e9c4e339728ecd532c5b174de5beb9cb4bab5db14e44fcd03ccb2e2c1b5"

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go run upcase_gen.go UnicodeData-5.1.0.txt")
		os.Exit(2)
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	if sum := sha256.Sum256(data); hex.EncodeToString(sum[:]) != ucdSHA256 {
		fail(fmt.Errorf("%s: SHA-256 %x, want %s (UnicodeData.txt of Unicode 5.1.0)", os.Args[1], sum, ucdSHA256))
	}
	upper := map[rune]rune{}
	lower := map[rune]rune{}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		f := strings.Split(sc.Text(), ";")
		if len(f) != 15 {
			fail(fmt.Errorf("bad line %q", sc.Text()))
		}
		c := hexRune(f[0])
		if f[12] != "" {
			upper[c] = hexRune(f[12])
		}
		if f[13] != "" {
			lower[c] = hexRune(f[13])
		}
	}
	if err := sc.Err(); err != nil {
		fail(err)
	}

	type entry struct{ from, to rune }
	var entries []entry
	for c := rune(0); c <= 0xFFFF; c++ {
		u, ok := upper[c]
		if !ok || u > 0xFFFF || lower[u] != c {
			continue
		}
		entries = append(entries, entry{c, u})
	}

	// Group entries into runs with the same offset and a step of 1 or 2.
	type run struct {
		lo, hi rune
		step   rune
		delta  rune
	}
	var runs []run
	for i := 0; i < len(entries); {
		e := entries[i]
		r := run{lo: e.from, hi: e.from, step: 1, delta: e.to - e.from}
		j := i + 1
		if j < len(entries) && entries[j].to-entries[j].from == r.delta && entries[j].from-e.from <= 2 {
			r.step = entries[j].from - e.from
			for j < len(entries) && entries[j].to-entries[j].from == r.delta && entries[j].from-r.hi == r.step {
				r.hi = entries[j].from
				j++
			}
		}
		runs = append(runs, r)
		i = j
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by upcase_gen.go from Unicode 5.1.0 UnicodeData.txt; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package names\n\n")
	fmt.Fprintf(&b, "// upcaseEntries is the number of characters ntfsUpcase changes.\n")
	fmt.Fprintf(&b, "const upcaseEntries = %d\n\n", len(entries))
	fmt.Fprintf(&b, "// ntfsUpcase maps a BMP character through the NTFS upcase table that Windows 7\n")
	fmt.Fprintf(&b, "// to 10 and mkntfs write. Every other character is returned unchanged.\n")
	fmt.Fprintf(&b, "func ntfsUpcase(r rune) rune {\n\tswitch {\n")
	for _, r := range runs {
		switch {
		case r.lo == r.hi:
			fmt.Fprintf(&b, "\tcase r == 0x%04X:\n", r.lo)
		case r.step == 1:
			fmt.Fprintf(&b, "\tcase 0x%04X <= r && r <= 0x%04X:\n", r.lo, r.hi)
		default:
			fmt.Fprintf(&b, "\tcase 0x%04X <= r && r <= 0x%04X && (r-0x%04X)%%2 == 0:\n", r.lo, r.hi, r.lo)
		}
		fmt.Fprintf(&b, "\t\treturn r %+d\n", r.delta)
	}
	fmt.Fprintf(&b, "\t}\n\treturn r\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("upcase_table.go", src, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("%d entries in %d runs\n", len(entries), len(runs))
}

func hexRune(s string) rune {
	v, err := strconv.ParseUint(s, 16, 32)
	if err != nil {
		fail(fmt.Errorf("bad code point %q: %w", s, err))
	}
	return rune(v)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "upcase_gen:", err)
	os.Exit(1)
}
