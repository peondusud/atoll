//go:build ignore

// propnames_gen writes propnames.go: the property names a regex may use in
// \p{…} and \P{…} (specs.md §29.5), the general categories and the scripts
// of Unicode 16.0.
//
// Usage, from internal/rules:
//
//	curl -o /tmp/Scripts-16.0.0.txt https://raw.githubusercontent.com/unicode-org/unicodetools/main/unicodetools/data/ucd/16.0.0/Scripts.txt
//	go run propnames_gen.go /tmp/Scripts-16.0.0.txt
//
// The input's SHA-256 must be scriptsSHA256 below. Unicode data is under the
// Unicode License v3.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

const scriptsSHA256 = "9e88f0a677df47311106340be8ede2ecdacd9c1c931831218d2be6d5508e0039"

// categories are the general categories §29.5 allows; Cn and Cs are left out.
var categories = []string{
	"C", "Cc", "Cf", "Co",
	"L", "Ll", "Lm", "Lo", "Lt", "Lu",
	"M", "Mc", "Me", "Mn",
	"N", "Nd", "Nl", "No",
	"P", "Pc", "Pd", "Pe", "Pf", "Pi", "Po", "Ps",
	"S", "Sc", "Sk", "Sm", "So",
	"Z", "Zl", "Zp", "Zs",
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: go run propnames_gen.go Scripts-16.0.0.txt")
		os.Exit(2)
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	if sum := sha256.Sum256(data); hex.EncodeToString(sum[:]) != scriptsSHA256 {
		fail(fmt.Errorf("%s: SHA-256 %x, want %s (Scripts.txt of Unicode 16.0.0)", os.Args[1], sum, scriptsSHA256))
	}
	seen := map[string]bool{}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		if strings.TrimSpace(line) == "" {
			continue
		}
		_, name, ok := strings.Cut(line, ";")
		if !ok {
			fail(fmt.Errorf("bad line %q", sc.Text()))
		}
		seen[strings.TrimSpace(name)] = true
	}
	if err := sc.Err(); err != nil {
		fail(err)
	}
	scripts := make([]string, 0, len(seen))
	for n := range seen {
		scripts = append(scripts, n)
	}
	sort.Strings(scripts)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by propnames_gen.go from Unicode 16.0.0 Scripts.txt; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package rules\n\n")
	fmt.Fprintf(&b, "// isCategory reports whether name is a general category a regex may use.\n")
	fmt.Fprintf(&b, "func isCategory(name string) bool {\n\tswitch name {\n\tcase %s:\n\t\treturn true\n\t}\n\treturn false\n}\n\n", quoteAll(categories))
	fmt.Fprintf(&b, "// isScript reports whether name is a script of Unicode 16.0, spelled as in\n// its Scripts.txt (%d scripts).\n", len(scripts))
	fmt.Fprintf(&b, "func isScript(name string) bool {\n\tswitch name {\n\tcase %s:\n\t\treturn true\n\t}\n\treturn false\n}\n", quoteAll(scripts))
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("propnames.go", src, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("%d categories, %d scripts\n", len(categories), len(scripts))
}

func quoteAll(names []string) string {
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = fmt.Sprintf("%q", n)
	}
	return strings.Join(q, ",\n\t\t")
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "propnames_gen:", err)
	os.Exit(1)
}
